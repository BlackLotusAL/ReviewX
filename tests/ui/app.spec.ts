import { test, expect } from '@playwright/test'
import fs from 'node:fs'

test('queue, report actions, history, rules and logs', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  const externalRequests: string[] = []
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:17081')) externalRequests.push(r.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '检视队列', exact: true })).toBeVisible()
  await expect(page.locator('.mr-card').filter({ hasText: '完善检视报告的读取校验与错误处理' }).getByText('2 条待处理', { exact: true })).toBeVisible()
  fs.mkdirSync('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/queue.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '完善检视报告的读取校验与错误处理', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'MR !404 检视报告' })
  await expect(drawer.getByRole('heading', { name: '检视意见 4' })).toBeVisible()
  await expect(drawer.getByText('<script>window.bad = 1</script>', { exact: false })).toBeVisible()
  await expect(page.locator('img[src*="evil.example"]')).toHaveCount(0)
  expect(externalRequests).toEqual([])
  await page.screenshot({ path: 'artifacts/report.png', fullPage: true, animations: 'disabled' })
  await drawer.getByRole('button', { name: '不发送', exact: true }).first().click()
  await expect(drawer.getByText('1 条待处理', { exact: false })).toBeVisible()
  await drawer.getByRole('button', { name: '撤销', exact: true }).first().click()
  await expect(drawer.getByText('2 条待处理', { exact: false })).toBeVisible()
  await drawer.getByRole('button', { name: '发送到 CodeHub', exact: true }).first().click()
  await expect(drawer.getByText('已发布', { exact: true }).first()).toBeVisible()
  await drawer.getByRole('button', { name: '标记已发布', exact: true }).click()
  await expect(drawer.getByText('已发布 · 人工确认', { exact: true }).first()).toBeVisible()
  await drawer.getByRole('button', { name: '其余全部不发送' }).click()
  const modal = page.getByRole('dialog', { name: '其余全部不发送' })
  await modal.getByRole('button', { name: '取消', exact: true }).click()
  await expect(drawer.getByText('1 条待处理', { exact: false })).toBeVisible()
  await drawer.getByRole('button', { name: '其余全部不发送' }).click()
  await page.getByRole('button', { name: '确认不发送 1 条' }).click()
  await expect(drawer.getByText('0 条待处理', { exact: false })).toBeVisible()
  await drawer.getByRole('tab', { name: '历史 1 · 已归档' }).click()
  await expect(drawer.getByText('历史报告 · 只读')).toBeVisible()
  await expect(drawer.getByRole('button', { name: '发送到 CodeHub' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(drawer).not.toBeVisible()
  await page.getByRole('button', { name: '规则配置', exact: true }).click()
  await page.getByRole('button', { name: '新建规则', exact: true }).first().click()
  await page.getByLabel('规则名称', { exact: true }).fill('事务一致性')
  await page.getByLabel('检查要点', { exact: true }).fill('数据库写入必须保持事务边界一致。')
  await page.getByLabel('适用文件', { exact: true }).fill('src/db/**')
  await page.getByRole('switch', { name: '保存后启用', exact: true }).click()
  await page.getByRole('button', { name: '保存规则', exact: true }).click()
  await expect(page.getByRole('button', { name: '事务一致性', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '规则配置', exact: true }).click()
  await expect(page.getByRole('switch', { name: '事务一致性规则已启用' })).toHaveAttribute('aria-checked', 'true')
  await page.screenshot({ path: 'artifacts/rules.png', fullPage: true })
  await page.getByRole('button', { name: '会话日志', exact: true }).click()
  await expect(page.getByRole('heading', { name: '会话日志', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'ERROR', exact: false }).click()
  await expect(page.getByText('OpenCode 检视未完成', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'artifacts/logs.png', fullPage: true })
  expect(errors).toEqual([])
})

test('project validation, failed and empty reports, narrow layout', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Project ID', { exact: true }).fill('abc')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('Project ID 应为正整数')).toBeVisible()
  await page.getByLabel('Project ID', { exact: true }).fill('101')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  await expect(page.getByText('该项目已在关注列表中：team/service（101）')).toBeVisible()
  await page.getByRole('button', { name: '优化代码快照的生成流程', exact: true }).click()
  await expect(page.getByText('本次未保存报告，没有可发布的意见。')).toBeVisible()
  await page.screenshot({ path: 'artifacts/failed.png', fullPage: true })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '更新项目文档与静态资源', exact: true }).click()
  await expect(page.getByRole('heading', { name: '无可检视的变更', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '补充请求参数的边界校验', exact: true }).click()
  await expect(page.getByRole('heading', { name: '暂无检视记录' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
